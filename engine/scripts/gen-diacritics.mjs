// Generate native/diacritics.h: the kitty graphics row/column diacritics,
// read from Ghostty's src/terminal/kitty/graphics_unicode.zig so the table
// matches the linked library. The index of a codepoint is its value.
import { readFileSync, writeFileSync } from 'node:fs';
const [src, out] = process.argv.slice(2);
const text = readFileSync(src, 'utf8');
const body = text.slice(text.indexOf('const diacritics: []const u21 = &.{'));
const list = body.slice(0, body.indexOf('};')).match(/0x[0-9A-Fa-f]+/g);
writeFileSync(out, `/* Generated by scripts/gen-diacritics.mjs. Do not edit. */\nstatic const uint32_t DIACRITICS[${list.length}] = {${list.join(',')}};\n#define DIACRITICS_LEN ${list.length}\n`);
console.log(`diacritics.h: ${list.length} entries`);
