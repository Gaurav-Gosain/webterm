// Generate src/custom-glyphs.js from xterm.js's addon-webgl custom glyphs
// (src/customGlyphs/Types.ts, CustomGlyphDefinitions.ts,
// CustomGlyphRasterizer.ts; MIT, see NOTICE). Box drawing, block elements,
// shades, sextants, octants, braille, legacy computing and powerline symbols
// are drawn as shapes, so they meet across cells and match the xterm.js
// client pixel for pixel. Use the addon-webgl version webterm's xterm.js
// client ships with.
// Run: node scripts/gen-custom-glyphs.mjs path/to/addon-webgl/src/customGlyphs
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const dir = process.argv[2];
let ts = ['Types.ts', 'CustomGlyphDefinitions.ts', 'CustomGlyphRasterizer.ts'].map((f) => readFileSync(`${dir}/${f}`, 'utf8')).join('\n');
// Imports between these files, and the two from xterm's core.
ts = ts.replace(/^import [^\n]+\n/gm, '');
ts = 'const throwIfFalsy = (v) => { if (!v) throw new Error("value must not be falsy"); return v; };\n' + ts;
// The worker has no document.
ts = ts.replaceAll("ctx.canvas.ownerDocument.createElement('canvas')", 'new OffscreenCanvas(1, 1)');
// The atlas holds coverage, not colour: without a background colour, a
// negative shape cuts its pixels out instead of painting them.
const cut = '  if (backgroundColor) {\n    ctx.fillStyle = backgroundColor;\n    ctx.strokeStyle = backgroundColor;\n  }';
if (!ts.includes(cut)) throw new Error('negative-shape block not found');
ts = ts.replace(cut, cut + " else {\n    ctx.globalCompositeOperation = 'destination-out';\n  }");
const js = stripTypeScriptTypes(ts, { mode: 'transform' });
writeFileSync(new URL('../src/custom-glyphs.js', import.meta.url), '// Generated by scripts/gen-custom-glyphs.mjs from xterm.js addon-webgl src/customGlyphs (MIT). Do not edit.\n' + js.replace(/\n\s*\n(\s*\n)+/g, '\n\n'));
