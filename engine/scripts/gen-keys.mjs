// Generate src/keys.js: DOM KeyboardEvent.code -> GhosttyKey value, read from
// Ghostty's key/event.h so the table always matches the linked library.
// GhosttyKey names are the W3C UI Events code names in UPPER_SNAKE_CASE.
import { readFileSync, writeFileSync } from 'node:fs';
const [header, out] = process.argv.slice(2);
const src = readFileSync(header, 'utf8');
const body = src.slice(src.indexOf('GHOSTTY_KEY_UNIDENTIFIED = 0'), src.indexOf('GHOSTTY_KEY_MAX_VALUE'));
const names = [...body.matchAll(/GHOSTTY_KEY_([A-Z0-9_]+)\s*(?:=\s*(\d+))?\s*,/g)];
const table = {};
let value = -1;
for (const [, name, explicit] of names) {
  value = explicit !== undefined ? +explicit : value + 1;
  if (name === 'UNIDENTIFIED') continue;
  // UPPER_SNAKE to the DOM code: BRACKET_LEFT -> BracketLeft, A -> KeyA,
  // DIGIT_0 -> Digit0, NUMPAD_0 -> Numpad0, LAUNCH_APP_1 -> LaunchApp1.
  let code = name.split('_').map((w) => (/^\d+$/.test(w) ? w : w[0] + w.slice(1).toLowerCase())).join('');
  if (/^[A-Z]$/.test(name)) code = 'Key' + name;
  table[code] = value;
}
// The DOM names a few keys differently from the W3C table Ghostty follows.
const aliases = { OSLeft: 'MetaLeft', OSRight: 'MetaRight', NumpadComma: 'NumpadComma' };
for (const [dom, w3c] of Object.entries(aliases)) if (table[w3c] !== undefined) table[dom] = table[w3c];
writeFileSync(out, `// Generated by scripts/gen-keys.mjs from Ghostty's include/ghostty/vt/key/event.h. Do not edit.\nexport const KEYS = ${JSON.stringify(table)};\n`);
console.log(`keys.js: ${Object.keys(table).length} codes`);
