// Generate src/transports.js from webterm's own transports (src/transport/
// websocket.ts, webtransport.ts, combinators.ts) by stripping the types, so
// the network worker connects, falls back and reconnects with exactly the
// code the xterm.js client uses. Run: node scripts/gen-transports.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
const here = new URL('..', import.meta.url);
const src = new URL('../src/transport/', here);
let out = '// Generated by scripts/gen-transports.mjs from webterm src/transport. Do not edit.\n';
for (const f of ['websocket.ts', 'webtransport.ts', 'combinators.ts']) {
  const js = stripTypeScriptTypes(readFileSync(new URL(f, src), 'utf8'), { mode: 'strip' });
  // Type-only imports strip to blank lines; any value import would break here.
  if (/^\s*import\s+[^t]/m.test(js)) throw new Error(`${f}: value import`);
  out += `\n// ---- ${f} ----\n` + js.replace(/^\s*\n/gm, '');
}
writeFileSync(new URL('src/transports.js', here), out);
